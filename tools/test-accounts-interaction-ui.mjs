// Start tools/preview-accounts-interaction-ui.mjs after building the renderer CSS.
// All IPC writes go to the fixture's in-memory call log; real accounts are never touched.
import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1664, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(6000)
  await page.goto('http://127.0.0.1:9388')
  await page.locator('[data-account-id=demo-4]').waitFor()
  assert.ok(await page.evaluate(() => !!window.fixture), 'Only run against the isolated fixture')
  const row = i => page.locator(`[data-account-id=demo-${i}]`)
  const point = i => row(i).locator('td').nth(2)
  const checkbox = i => row(i).getByRole('checkbox')
  const detail = i => row(i).locator('[data-slot=account-detail-trigger]')
  const toolbar = page.locator('[data-slot=account-toolbar]')
  const drawer = page.locator('[data-slot=sheet-content][data-state=open]')
  const selection = () => page.locator('[data-account-id][aria-selected=true]').evaluateAll(items => items.map(item => item.dataset.accountId))
  const selected = async ids => assert.deepEqual(await selection(), ids.map(i => `demo-${i}`))
  const all = page.getByRole('checkbox', { name: 'Chọn tất cả tài khoản đang hiển thị', exact: true })
  const search = page.getByRole('textbox', { name: 'Tìm tài khoản', exact: true })
  const clear = () => toolbar.getByRole('button', { name: 'Bỏ chọn', exact: true }).click()
  const geometry = () => toolbar.evaluate(el => ({ height: el.getBoundingClientRect().height, searchX: el.querySelector('input').getBoundingClientRect().x, clearX: [...el.querySelectorAll('button')].find(button => button.textContent==='Bỏ chọn').getBoundingClientRect().x }))
  const initialGeometry = await geometry()

  await selected([])
  assert.equal(await toolbar.getByRole('button', { name: 'Chạy đã chọn', exact: true }).isDisabled(), true)
  await point(0).click()
  await selected([0]); assert.equal(await drawer.count(), 0)
  await point(2).click({ modifiers: ['Control'] })
  await selected([0, 2])
  await point(4).click({ modifiers: ['Shift'] })
  await selected([2, 3, 4])
  assert.equal(await all.getAttribute('aria-checked'), 'mixed')
  await checkbox(1).click()
  await checkbox(0).click({ modifiers: ['Shift'] })
  await selected([0, 1, 2, 3, 4])
  assert.equal(await all.getAttribute('aria-checked'), 'true')
  assert.deepEqual(await geometry(), initialGeometry, 'Selection must not move toolbar controls')

  await search.fill('Bình')
  await all.click()
  assert.match(await toolbar.innerText(), /Đã chọn 4 tài khoản · 4 đang ẩn bởi bộ lọc/)
  await all.click()
  assert.match(await toolbar.innerText(), /Đã chọn 5 tài khoản · 4 đang ẩn bởi bộ lọc/)
  await search.fill('')
  await selected([0, 1, 2, 3, 4])
  await clear()

  await checkbox(0).click(); await checkbox(1).click()
  await point(3).click({ button: 'right' })
  await selected([0, 1])
  assert.match(await page.getByRole('menu').innerText(), /^Dũng Phạm/)
  await page.getByRole('menuitem', { name: 'Xem chi tiết', exact: true }).click()
  assert.equal(await drawer.locator('[data-slot=sheet-title]').innerText(), 'Dũng Phạm')
  await selected([0, 1])
  await detail(0).click(); await detail(1).click(); await detail(0).click()
  assert.equal(await drawer.locator('[data-slot=sheet-title]').innerText(), 'An Nguyễn')
  await drawer.getByRole('button', { name: 'Xem tài khoản tiếp theo' }).click()
  assert.equal(await drawer.locator('[data-slot=sheet-title]').innerText(), 'Bình Trần')
  await selected([0, 1])
  await drawer.getByRole('button', { name: 'Tuỳ chọn chức năng chạy', exact: true }).click()
  await page.getByRole('menu').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('menu').count(), 0)
  assert.equal(await drawer.count(), 1, 'First Esc closes only the nested menu')
  await page.keyboard.press('Escape')
  assert.equal(await drawer.count(), 0)

  await row(2).focus(); await page.keyboard.press('Space'); await selected([2])
  await page.keyboard.press('Enter')
  assert.equal(await drawer.locator('[data-slot=sheet-title]').innerText(), 'Chi Lê')
  await checkbox(0).click()
  assert.equal(await drawer.count(), 1, 'Checkbox does not open, close or switch details')
  await page.keyboard.press('Escape')
  assert.equal(await drawer.count(), 0, 'Esc also works when focus is in the table')
  await point(3).dblclick()
  assert.equal(await drawer.locator('[data-slot=sheet-title]').innerText(), 'Dũng Phạm')
  await drawer.getByRole('button', { name: 'Đóng chi tiết tài khoản' }).click()
  await clear(); await checkbox(1).click()
  await detail(0).click(); await page.keyboard.press('Escape')
  // Viewing account 0 must not redirect the single selected account's edit/login actions.
  await toolbar.getByRole('button', { name: 'Thao tác khác', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Sửa tài khoản', exact: true }).click()
  assert.equal(await page.locator('[data-slot=dialog-content] input').first().inputValue(), 'Bình Trần')
  await page.keyboard.press('Escape')
  await toolbar.getByRole('button', { name: 'Thao tác trình duyệt', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Mở cửa sổ đăng nhập', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => window.fixture.calls.filter(call => call.name==='openLoginWindow').at(-1)?.args), ['demo-1'])
  assert.equal(await toolbar.getByRole('button', { name: 'Dừng đã chọn', exact: true }).isDisabled(), true, 'A non-running selection cannot silently stop other accounts')

  await detail(0).click()
  await page.getByRole('button', { name: 'Lịch sử', exact: true }).click()
  assert.equal(await drawer.count(), 0, 'Changing tab closes the account drawer')
  await page.getByRole('button', { name: 'Tài khoản', exact: true }).click()
  assert.equal(await drawer.count(), 0, 'Returning to the tab does not reopen details')
  await page.evaluate(() => { window.fixture.replaceRows(window.fixture.rows().filter(row => row.id!=='demo-1')) })
  await page.waitForFunction(() => !document.querySelector('[data-account-id=demo-1]'))
  assert.match(await toolbar.innerText(), /Chưa chọn tài khoản/)

  for (const width of [1184, 1664]) {
    await page.setViewportSize({ width, height: 900 })
    await page.waitForFunction(() => document.fonts.status==='loaded')
    const before = await geometry()
    await all.click()
    assert.deepEqual(await geometry(), before, `Stable selection toolbar at ${width}px`)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth), 'No page horizontal overflow')
    await clear()
  }
  assert.deepEqual(errors, [])
  console.log('PASS: row/modifier/checkbox/range/filter selection; scoped context menu; drawer navigation/Esc/menu focus; toolbar edit/login/stop targets; tab change; stale IDs; stable toolbar at 1184/1664px.')
} finally {
  await browser.close()
}
