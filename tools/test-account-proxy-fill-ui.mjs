// Requires the isolated fixture on port 9388. This does not contact proxies or mutate real accounts.
import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser=await chromium.launch({channel:'msedge',headless:true})
try {
  const page=await browser.newPage({viewport:{width:1184,height:900}}),errors=[]
  page.on('pageerror',error=>errors.push(error.message));page.setDefaultTimeout(6000)
  await page.goto('http://127.0.0.1:9388');await page.locator('[data-account-id=demo-4]').waitFor()
  assert.ok(await page.evaluate(()=>!!window.fixture))
  const row=i=>page.locator(`[data-account-id=demo-${i}]`)
  const dialog=page.locator('[data-slot=dialog-content]')
  const selected=()=>page.locator('[data-account-id][aria-selected=true]').evaluateAll(items=>items.map(item=>item.dataset.accountId))
  const open=async i=>{
    await row(i).locator('td').nth(2).click({button:'right'})
    await page.getByRole('menuitem',{name:'Chọn và gán proxy…',exact:true}).click()
    await dialog.getByRole('heading',{name:'Chọn và gán proxy',exact:true}).waitFor()
  }
  await row(0).getByRole('checkbox').click();await row(1).getByRole('checkbox').click()
  await row(0).locator('[data-slot=account-detail-trigger]').click()
  await open(3)
  assert.equal(await page.locator('[data-slot=sheet-content][data-state=open]').count(),0,'Only one drawer/dialog layer stays open')
  assert.match(await dialog.locator('[data-slot=dialog-description]').innerText(),/Dũng Phạm/)
  assert.deepEqual(await selected(),['demo-0','demo-1'])
  const count=dialog.getByRole('spinbutton',{name:'Số proxy cho tài khoản',exact:true})
  await count.fill('2.5')
  assert.equal(await dialog.getByRole('button',{name:/Kiểm tra & gán/}).isDisabled(),true)
  await count.fill('21')
  assert.equal(await dialog.getByRole('button',{name:/Kiểm tra & gán/}).isDisabled(),true)
  await count.fill('3')
  await dialog.getByRole('button',{name:'Kiểm tra & gán 3 proxy',exact:true}).click()
  await dialog.getByText('Đã gán thành công',{exact:true}).waitFor()
  assert.deepEqual(await page.evaluate(()=>window.fixture.calls.filter(call=>call.name==='accountProxyFill').at(-1).args),[{profileId:'demo-3',count:3}])
  assert.equal(await dialog.getByText('Chính',{exact:true}).count(),1)
  assert.equal(await dialog.getByText('Dự phòng 2',{exact:true}).count(),1)
  assert.equal(await dialog.getByText('Bing OK · 45 ms',{exact:true}).count(),1)
  assert.deepEqual(await selected(),['demo-0','demo-1'])
  const bounds=await dialog.boundingBox()
  assert.ok(bounds.y>=0 && bounds.y+bounds.height<=900,'Dialog fits the viewport')
  await page.keyboard.press('Escape');assert.equal(await dialog.count(),0)

  await page.evaluate(()=>window.fixture.proxyJobMode='slow')
  await open(0);await count.fill('2')
  await dialog.getByRole('button',{name:'Kiểm tra & gán 2 proxy',exact:true}).click()
  await page.keyboard.press('Escape')
  await open(0)
  await page.waitForFunction(()=>document.querySelector('[aria-label="Số proxy cho tài khoản"]').value==='2')
  await dialog.getByRole('button',{name:'Dừng kiểm tra',exact:true}).click()
  await dialog.getByText('Đã dừng kiểm tra. Giữ nguyên proxy tài khoản.',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>window.fixture.rows().find(row=>row.id==='demo-0').profile.proxyId??null),null)
  await dialog.getByRole('button',{name:'Đóng',exact:true}).click()
  await open(2)
  await dialog.getByText('Dừng tài khoản và đóng browser trước khi đổi proxy. Có thể đóng hộp thoại rồi quay lại.',{exact:true}).waitFor()
  assert.equal(await dialog.getByRole('button',{name:/Kiểm tra & gán/}).isDisabled(),true)
  await page.keyboard.press('Escape')
  assert.deepEqual(await selected(),['demo-0','demo-1'])
  assert.deepEqual(errors,[])
  console.log('PASS: context-menu target independent of checked rows; count validation; success/latency/primary/backups; cancellation; busy guard; Esc; compact dialog at 1184px.')
} finally {await browser.close()}
