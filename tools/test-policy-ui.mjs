// Kiểm tra cài đặt bằng cache và form; không gửi search hoặc mở browser Rewards.
import assert from 'node:assert/strict'
import path from 'node:path'
import { chromium } from 'playwright-core'

const app = await chromium.connectOverCDP(`http://127.0.0.1:${process.env.BRF_DEBUG_PORT ?? 9377}`)
const page = app.contexts()[0].pages().find(page => /out\/renderer|localhost/.test(page.url()))
page.setDefaultTimeout(10000)
const before = await page.evaluate(() => window.api.getAutomationPolicy())
const settingsBefore = await page.evaluate(() => window.api.getSettings())
const profiles = await page.evaluate(() => window.api.listProfiles())
assert.ok(profiles.length)
const choose = async (trigger, label) => {
  await trigger.click()
  const bounds = await page.getByRole('listbox').boundingBox()
  const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  assert.ok(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= viewport.width + 1 && bounds.y + bounds.height <= viewport.height + 1, 'Menu chọn phải nằm trong cửa sổ')
  await page.getByRole('option', { name: label, exact: true }).click()
  assert.equal(await trigger.innerText(), label)
}
let restored = false
try {
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Cài đặt', exact: true }).click()
  const panel = page.locator('[data-slot="policy-settings"]')
  await panel.getByRole('heading', { name: 'Cài đặt kịch bản', exact: true }).waitFor()
  await panel.locator('[data-preset="three-searches"]').click()
  assert.equal(await panel.getByRole('spinbutton', { name: 'Tổng lượt tìm kiếm / ngày', exact: true }).inputValue(), '3')
  assert.equal(await panel.getByRole('spinbutton', { name: 'Số lượt tối đa / phiên', exact: true }).inputValue(), '3')
  await panel.locator('[data-preset="bot-reduce"]').click()
  assert.equal(await panel.getByRole('spinbutton', { name: 'Mục tiêu khi score cao (%)', exact: true }).inputValue(), '20')
  assert.equal(await panel.getByRole('switch', { name: 'Áp dụng quy tắc Bot score', exact: true }).isChecked(), true)
  // Reproduce CN–T7: every click must change state, colour, and the visible summary.
  const days = panel.getByRole('toolbar', { name: 'Ngày trong tuần', exact: true })
  const dayButtons = days.getByRole('button')
  assert.equal(await dayButtons.count(), 7)
  for (let i = 0; i < 6; i++) {
    await dayButtons.nth(i).click()
    assert.equal(await dayButtons.nth(i).getAttribute('aria-pressed'), 'false')
  }
  assert.match(await panel.locator('#policy-weekdays-summary').innerText(), /Đã chọn: T7\./)
  await dayButtons.nth(6).click()
  assert.equal(await dayButtons.nth(6).getAttribute('aria-pressed'), 'true', 'Không cho bỏ ngày cuối cùng')
  await page.mouse.move(0, 0)
  await page.waitForFunction(() => {
    const buttons = document.querySelectorAll('[data-slot="toggle-group-item"]')
    return getComputedStyle(buttons[6]).backgroundColor === 'rgb(10, 10, 10)' && getComputedStyle(buttons[0]).backgroundColor === 'rgb(255, 255, 255)'
  })
  await dayButtons.nth(0).focus()
  await page.keyboard.press('Space')
  assert.equal(await dayButtons.nth(0).getAttribute('aria-pressed'), 'true')
  await page.keyboard.press('ArrowRight')
  assert.equal(await dayButtons.nth(1).evaluate(el => el === document.activeElement), true)
  await page.keyboard.press('Space')
  assert.equal(await dayButtons.nth(1).getAttribute('aria-pressed'), 'true')
  const selectedDays = [1, 3, 5]
  // Add first so even a starting one-day schedule stays valid.
  for (const i of selectedDays) if (await dayButtons.nth(i).getAttribute('aria-pressed') !== 'true') await dayButtons.nth(i).click()
  for (let i = 0; i < 7; i++) if (!selectedDays.includes(i) && await dayButtons.nth(i).getAttribute('aria-pressed') === 'true') await dayButtons.nth(i).click()
  assert.match(await panel.locator('#policy-weekdays-summary').innerText(), /Đã chọn: T2, T4, T6\./)
  await choose(panel.locator('#policy-bot-action'), 'Tạm dừng toàn bộ nhiệm vụ')
  await panel.locator('#policy-bot-action').press('Space')
  await page.getByRole('listbox').waitFor()
  await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'option')
  await page.keyboard.press('Home')
  await page.waitForFunction(() => document.activeElement?.textContent === 'Giảm mục tiêu search')
  await page.keyboard.press('Enter')
  assert.equal(await panel.locator('#policy-bot-action').innerText(), 'Giảm mục tiêu search')
  await panel.locator('#policy-bot-action').press('ArrowDown')
  await page.getByRole('listbox').waitFor()
  await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'option')
  await page.keyboard.press('End')
  await page.waitForFunction(() => document.activeElement?.textContent === 'Tạm dừng toàn bộ nhiệm vụ')
  await page.keyboard.press('Enter')
  assert.equal(await panel.locator('#policy-bot-action').innerText(), 'Tạm dừng toàn bộ nhiệm vụ')
  await choose(panel.locator('#policy-bot-unknown'), 'Dùng mục tiêu cơ bản')
  await choose(panel.locator('#policy-proxy'), 'Kiểm tra kho & gán lại')
  await choose(panel.locator('#policy-every'), 'Mỗi 15 phút')
  assert.equal((await page.evaluate(() => window.api.getSettings())).autoEveryMs, settingsBefore.autoEveryMs, 'Đổi chu kỳ trên form không tự lưu')
  const everyLabels = { 0: 'Tắt lịch tự động', 60000: 'Mỗi 1 phút', 900000: 'Mỗi 15 phút', 3600000: 'Mỗi 1 giờ', 10800000: 'Mỗi 3 giờ' }
  await choose(panel.locator('#policy-every'), everyLabels[settingsBefore.autoEveryMs ?? 0])
  await panel.getByRole('spinbutton', { name: 'Tổng lượt tìm kiếm / ngày', exact: true }).fill('3')
  const enable = panel.getByRole('switch', { name: 'Bật bộ quy tắc', exact: true })
  if (!await enable.isChecked()) await enable.click()
  await panel.getByRole('button', { name: 'Xem trước', exact: true }).click()
  await panel.locator('tbody tr').first().waitFor()
  assert.equal(await panel.locator('tbody tr').count(), profiles.length)
  assert.deepEqual(await page.evaluate(() => window.api.getAutomationPolicy()), before, 'Xem trước không tự lưu')
  await panel.locator('#policy-scope').click()
  await page.getByRole('option').nth(1).click()
  const own = panel.getByRole('switch', { name: 'Dùng cấu hình riêng', exact: true })
  if (await own.isChecked()) await own.click()
  assert.equal(await dayButtons.first().isDisabled(), true)
  assert.equal(await panel.locator('#policy-bot-action').isDisabled(), true)
  assert.equal(await panel.getByText('Đang dùng mặc định chung. Bật “Dùng cấu hình riêng” để chỉnh tài khoản này.', { exact: true }).isVisible(), true)
  await panel.getByRole('switch', { name: 'Dùng cấu hình riêng', exact: true }).check()
  await panel.locator('[data-preset="daily-only"]').click()
  assert.equal(await panel.getByRole('switch', { name: 'Search desktop', exact: true }).isChecked(), false)
  assert.equal(await panel.getByRole('switch', { name: 'Daily set', exact: true }).isChecked(), true)
  // Lưu thử khi bộ quy tắc TẮT; chu kỳ giữ nguyên, không khởi chạy nhiệm vụ.
  if (await enable.isChecked()) await enable.click()
  await panel.getByRole('button', { name: 'Lưu cài đặt', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-slot="policy-settings"]')?.textContent?.includes('Cài đặt đã lưu'))
  const saved = await page.evaluate(() => window.api.getAutomationPolicy())
  assert.equal(saved.enabled, false)
  assert.equal(saved.defaults.maxSearchesPerDay, 3)
  assert.deepEqual(saved.defaults.weekdays, selectedDays)
  assert.equal(saved.defaults.botRule.action, 'pause')
  assert.equal(saved.defaults.botRule.unknown, 'base')
  assert.equal(saved.defaults.proxyRecovery, 'repair')
  assert.equal(saved.overrides[profiles[0].id].tasks.desktop, false)
  assert.equal((await page.evaluate(() => window.api.getSettings())).autoEveryMs, settingsBefore.autoEveryMs)
  await page.reload()
  await page.getByRole('button', { name: 'Cài đặt', exact: true }).click()
  await panel.getByRole('heading', { name: 'Cài đặt kịch bản', exact: true }).waitFor()
  for (let i = 0; i < 7; i++) assert.equal(await dayButtons.nth(i).getAttribute('aria-pressed'), String(selectedDays.includes(i)), 'Ngày đã lưu phải còn sau khi tải lại')
  assert.equal(await panel.locator('#policy-bot-action').innerText(), 'Tạm dừng toàn bộ nhiệm vụ')
  const originalSize = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  for (const width of [1680, 1184]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    const body = panel.locator('[data-slot="scroll-area-viewport"]').first()
    await body.evaluate(el => { el.scrollTop = 0 })
    assert.ok(await body.evaluate(el => el.scrollWidth <= el.clientWidth + 1))
    await page.screenshot({ path: path.resolve(`docs/screenshot-policy-${width}.png`) })
  }
  await page.setViewportSize(originalSize)
  // Select portals inside the run menu must remain clickable and keep their menu open.
  await page.getByRole('button', { name: 'Cài đặt chạy', exact: true }).click()
  const menu = page.getByRole('menu').filter({ has: page.getByRole('combobox', { name: 'Cập nhật song song', exact: true }) })
  const parallel = settingsBefore.refreshParallel === 2 ? 3 : 2
  await choose(menu.getByRole('combobox', { name: 'Cập nhật song song', exact: true }), `${parallel} acc`)
  await page.waitForFunction(v => window.api.getSettings().then(s => s.refreshParallel === v), parallel)
  assert.equal(await menu.isVisible(), true)
  await menu.getByRole('combobox', { name: 'Tự động chạy', exact: true }).click()
  assert.equal(await page.getByRole('option').count(), 5)
  await page.keyboard.press('Escape')
  assert.equal(await menu.isVisible(), true)
  await menu.getByRole('combobox', { name: 'Giới hạn tổng', exact: true }).click()
  assert.equal(await page.getByRole('option').count(), 6)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await page.evaluate(value => window.api.setSettings({ refreshParallel: value }), settingsBefore.refreshParallel)
  await page.evaluate(config => window.api.saveAutomationPolicy(config), before)
  restored = true
  console.log('PASS: CN–T7 bấm/đổi màu/bàn phím, giữ ít nhất 1 ngày, lưu và tải lại, 8 Select shadcn, cấu hình riêng, xem trước không lưu, không tràn ở 1184–1680px; đã khôi phục cài đặt')
} finally {
  if (!restored) {
    await page.evaluate(config => window.api.saveAutomationPolicy(config), before)
    await page.evaluate(value => window.api.setSettings({ refreshParallel: value }), settingsBefore.refreshParallel)
  }
}
await page.reload()
await page.getByRole('button', { name: 'Cài đặt', exact: true }).click()
process.exit(0)
